// apps/web/src/spa/main.tsx — the Vite entry for the auth'd SPA bundle (REQ-TL-2/3; the rollup input
// in vite.config.ts). This is the SPA.1 toolchain smoke scaffold — the real skeleton (the full route
// tree, the beforeLoad session gate, bffFetch, GET /session boot, SsrHandoff, the head manager) is
// SPA.4's. Nothing serves this bundle until SPA.3's shell document emits the manifest-resolved
// <script type="module"> tag; the output under public/spa/ is inert.
import { createRouter, RouterProvider } from "@tanstack/react-router";
import { createRoot } from "react-dom/client";
// Generated by @tanstack/router-plugin from src/spa/routes/ at every vite build and committed so
// `tsc -p tsconfig.spa.json` stays a pure typecheck (design/21 F4, REQ-TL-9).
import { routeTree } from "./routeTree.gen.js";

export const spaRouter = createRouter({ routeTree });

declare module "@tanstack/react-router" {
  interface Register {
    router: typeof spaRouter;
  }
}

// The shell document (SPA.3) stamps <div data-spa-root>; mounting is a no-op when it is absent so a
// served-without-mount document degrades inertly (the islands' degrade-never-fail convention).
export function mountSpa(root: HTMLElement): void {
  createRoot(root).render(<RouterProvider router={spaRouter} />);
}

const mountPoint = document.querySelector("[data-spa-root]");
if (mountPoint instanceof HTMLElement) mountSpa(mountPoint);
