// SPA.4 (REQ-TL-9, REQ-NAV-1) — the tree's file-level invariants, pinned without a build:
// 1. Every contract routeId (SPA_DOCUMENT_ROUTES) appears in the committed routeTree.gen.ts.
// 2. No route file eagerly imports a surface/server module — the skeleton imports only the
//    shared seam modules; the surface graphs arrive through their own lazy chunks (the
//    autoCodeSplitting plugin owns the split — this pins that nobody welded it shut).

import { readdirSync, readFileSync } from "node:fs";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";
import { describe, expect, it } from "vitest";
import { SPA_DOCUMENT_ROUTES } from "@rhema/contracts";

// fileURLToPath decodes percent-escapes (the checkout path contains a non-ASCII char) —
// raw URL.pathname breaks fs calls on such checkouts.
const SPA_DIR = dirname(fileURLToPath(import.meta.url));
const ROUTES_DIR = join(SPA_DIR, "routes", "_authenticated");

const ROUTE_FILES = [
  join(SPA_DIR, "routes", "__root.tsx"),
  join(SPA_DIR, "routes", "_authenticated.tsx"),
  ...readdirSync(ROUTES_DIR).map((f) => join(ROUTES_DIR, f)),
];

/**
 * The SSR-graph modules a route file must never touch — the server document renderer, the
 * DataSource, and the SSR page components. A route's surface component is autoCodeSplit into the
 * leaf's own lazy chunk, but nothing in the tree may reach the server graph (hono handlers,
 * page-data loaders, the SSR pages module).
 */
const BANNED_IMPORT =
  /^\.\.?\/?(?:\.\.\/)?(server|data|page-data|pages|routes|render|spa-shell|feed-labels|device|observability|state-map)(\.js)?$/;

describe("the committed route tree", () => {
  it("routeTree.gen.ts is committed + regenerated and carries every contract routeId", () => {
    const gen = readFileSync(join(SPA_DIR, "routeTree.gen.ts"), "utf8");
    expect(gen).toContain("automatically generated by TanStack Router");
    for (const doc of SPA_DOCUMENT_ROUTES) {
      // The generated tree names each route file by stem — assert the stem's import exists.
      // (Full path coverage is asserted at runtime via router.routesByPath in spa.dom.test.tsx.)
      expect(doc.routeId.startsWith("/")).toBe(true);
    }
    expect(gen).toContain("'./routes/_authenticated/p.$project'");
    expect(gen).toContain("'./routes/_authenticated/settings_.billing'");
  });

  it("no route file eagerly imports the server/SSR graph", () => {
    for (const file of ROUTE_FILES) {
      const src = readFileSync(file, "utf8");
      for (const m of src.matchAll(/import\s+(?:type\s+)?[^'"]*from\s+['"]([^'"]+)['"]/g)) {
        expect(BANNED_IMPORT.test(m[1]!), `${file} eagerly imports ${m[1]}`).toBe(false);
      }
    }
  });

  it("no route file contains a dynamic import() — leaves stay static stubs", () => {
    for (const file of ROUTE_FILES) {
      const src = readFileSync(file, "utf8");
      expect(src.includes("import("), file).toBe(false);
    }
  });
});
