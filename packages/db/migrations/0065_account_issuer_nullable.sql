-- 0065_account_issuer_nullable.sql — better-auth 1.7.25 runtime schema check (301_R6DEP.1).
--
-- 0025 made `account.issuer` NOT NULL for better-auth 1.7.2, whose account key was {issuer,
-- account_id}. 1.7.x (≥1.7.3) stopped writing `issuer` entirely — and 1.7.25 added a runtime
-- schema check (`ctx.checkSchema`, run on every auth request) that diffs the live schema against
-- the adapter's expected shape. A NOT NULL column the library never writes is flagged
-- "Required columns Better Auth never writes" — SchemaMismatchError — and account INSERTs
-- would fail at runtime regardless. Verified live: the preview api 500'd every /api/auth/*
-- endpoint, and the same check reproduced against the prod schema (read-only introspection).
--
-- Fix per the library's own remediation ("make the listed columns nullable"): widen the
-- column, keep the backfilled data and the account_issuer_account_idx index. No app code
-- reads `issuer`; new rows carry NULL. The column itself stays — dropping it is a
-- destructive change the additive lane rejects, and the backfill provenance is worth keeping.
alter table public.account alter column issuer drop not null;
